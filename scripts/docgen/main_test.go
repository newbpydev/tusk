func TestDocgen_PromotionFailureRetainsRecovery(t *testing.T) {
	root := t.TempDir()
	if err := execute(root, false, os.Rename); err != nil {
		t.Fatal(err)
	}
	beforeMan, beforeComp := readTree(t, filepath.Join(root, "man")), readTree(t, filepath.Join(root, "completions"))
	calls := 0
	err := execute(root, false, func(old, new string) error {
		calls++
		if calls == 4 {
			return errors.New("second install failed")
		}
		return os.Rename(old, new)
	})
	if err == nil || !strings.Contains(err.Error(), "recovery files retained") {
		t.Fatalf("missing recovery error: %v", err)
	}
	if !reflect.DeepEqual(beforeMan, readTree(t, filepath.Join(root, "man"))) || !reflect.DeepEqual(beforeComp, readTree(t, filepath.Join(root, "completions"))) {
		t.Fatal("previous accepted bytes lost")
	}
	stages, err := filepath.Glob(filepath.Join(root, ".docgen-*"))
	if err != nil || len(stages) != 1 {
		t.Fatalf("recovery files not retained: %v %v", stages, err)
	}
}

