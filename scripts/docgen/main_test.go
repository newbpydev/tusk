func TestDocgen_MainExit(t *testing.T) {
	if os.Getenv("TUSK_DOCGEN_MAIN") == "1" {
		os.Args = []string{"docgen", "--wat"}
		main()
		return
	}
	cmd := exec.Command(os.Args[0], "-test.run=^TestDocgen_MainExit$")
	cmd.Env = append(os.Environ(), "TUSK_DOCGEN_MAIN=1")
	err := cmd.Run()
	var exit *exec.ExitError
	if !errors.As(err, &exit) || exit.ExitCode() != 2 {
		t.Fatalf("main usage exit: %v", err)
	}
}
