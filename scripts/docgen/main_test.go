func readTree(t *testing.T, root string) map[string]string {
	t.Helper()
	files := map[string]string{}
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		files[filepath.ToSlash(rel)] = string(data)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return files
}

func TestDocgen_DeterministicPureTree(t *testing.T) {
	t.Setenv("TUSK_DB_PATH", filepath.Join(t.TempDir(), "never", "tasks.db"))
	t.Setenv("TUSK_TIMEZONE", "bad")
	t.Setenv("TUSK_AUTO_COMPLETE_PARENT", "bad")
	t.Setenv("SOURCE_DATE_EPOCH", "bad-wall-clock")
	first, second := t.TempDir(), t.TempDir()
	var errs bytes.Buffer
	for _, root := range []string{first, second} {
		if code := run([]string{"--output", root}, &errs); code != 0 {
			t.Fatalf("code %d: %s", code, errs.String())
		}
	}
	files := readTree(t, first)
	if !reflect.DeepEqual(files, readTree(t, second)) {
		t.Fatal("checkout/time dependent generation")
	}
	for _, name := range []string{"man/tusk.1", "man/tusk-completion.1", "man/tusk-tui.1", "completions/tusk.bash", "completions/tusk.zsh", "completions/tusk.fish"} {
		if files[name] == "" {
			t.Errorf("missing %s", name)
		}
	}
	for _, data := range files {
		if strings.Contains(data, "Auto generated") {
			t.Error("autogenerated date/footer leak")
		}
	}
	if _, err := os.Stat(os.Getenv("TUSK_DB_PATH")); !errors.Is(err, fs.ErrNotExist) {
		t.Fatalf("storage created: %v", err)
	}
	if code := run([]string{"--output", first, "--check"}, &errs); code != 0 {
		t.Fatalf("clean output: %s", errs.String())
	}
}

