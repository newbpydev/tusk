func TestDocgen_DriftAndOwnedRepair(t *testing.T) {
	root := t.TempDir()
	var errs bytes.Buffer
	if run([]string{"--output", root}, &errs) != 0 {
		t.Fatal(errs.String())
	}
	before := readTree(t, root)
	for _, change := range []string{"changed", "missing", "extra"} {
		path := filepath.Join(root, "man", "tusk.1")
		switch change {
		case "changed":
			if err := os.WriteFile(path, []byte("stale"), 0644); err != nil {
				t.Fatal(err)
			}
		case "missing":
			if err := os.Remove(path); err != nil {
				t.Fatal(err)
			}
		case "extra":
			if err := os.WriteFile(filepath.Join(root, "man", "stale.1"), nil, 0644); err != nil {
				t.Fatal(err)
			}
		}
		if code := run([]string{"--check", "--output", root}, &errs); code != 1 {
			t.Errorf("%s not detected: %d", change, code)
		}
		if err := os.WriteFile(filepath.Join(root, "user-guide.md"), []byte("preserve"), 0644); err != nil {
			t.Fatal(err)
		}
		if code := run([]string{"--output", root}, &errs); code != 0 {
			t.Fatalf("repair: %s", errs.String())
		}
		after := readTree(t, root)
		if after["user-guide.md"] != "preserve" {
			t.Fatal("unowned guide changed")
		}
		delete(after, "user-guide.md")
		if !reflect.DeepEqual(before, after) {
			t.Fatalf("owned outputs were not restored: %s", change)
		}
	}
}

func TestDocgen_InvalidAndFailureRecovery(t *testing.T) {
	var errs bytes.Buffer
	for _, args := range [][]string{{"--wat"}, {"extra"}, {"--output", ""}} {
		if code := run(args, &errs); code != 2 {
			t.Errorf("%v: exit %d", args, code)
		}
	}
	file := filepath.Join(t.TempDir(), "file")
	if err := os.WriteFile(file, []byte("preserve"), 0644); err != nil {
		t.Fatal(err)
	}
	if code := run([]string{"--output", file}, &errs); code != 1 {
		t.Fatalf("non-directory accepted: %d", code)
	}
	if data, _ := os.ReadFile(file); string(data) != "preserve" {
		t.Fatal("original replaced")
	}
	if code := run([]string{"--check", "--output", filepath.Join(t.TempDir(), "absent")}, &errs); code != 1 {
		t.Fatalf("absent output accepted: %d", code)
	}

	root := t.TempDir()
	if run([]string{"--output", root}, &errs) != 0 {
		t.Fatal(errs.String())
	}
	before := readTree(t, root)
	staged := t.TempDir()
	if err := generate(cli.CommandTree(), staged); err != nil {
		t.Fatal(err)
	}
	calls := 0
	rename := func(old, new string) error {
		calls++
		if calls == 4 {
			return errors.New("injected second install failure")
		}
		return os.Rename(old, new)
	}
	if err := publish(staged, root, rename); err == nil {
		t.Fatal("promotion failure ignored")
	}
	if !reflect.DeepEqual(before, readTree(t, root)) {
		t.Fatal("accepted docs lost after second promotion failure")
	}
}

